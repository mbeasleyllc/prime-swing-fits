export function getClubsByCategory(category: string): Product[] {
  return CLUB_DATABASE.filter(club => club.category?.toLowerCase() === category.toLowerCase());
}

export function searchClubsLocal(query: string): Product[] {
  const lowerQuery = query.toLowerCase();
  return CLUB_DATABASE.filter(club => 
    club.brand?.toLowerCase().includes(lowerQuery) ||
    club.model_name?.toLowerCase().includes(lowerQuery) ||
    club.category?.toLowerCase().includes(lowerQuery)
  );
}